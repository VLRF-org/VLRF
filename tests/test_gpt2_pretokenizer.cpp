// VLRF Tests — GPT-2 pre-tokenizer  (test_gpt2_pretokenizer.cpp)
// Verifies gpt2_pretokenize::split() against ground truth produced by
// Python's `regex` module running GPT-2's actual pre-tokenizer pattern:
//
//   's|'t|'re|'ve|'m|'ll|'d| ?\p{L}+| ?\p{N}+| ?[^\s\p{L}\p{N}]+|\s+(?!\S)|\s+
//
// Expected outputs below were generated once via:
//   python3 -c "import regex as re; ..." (see PR/commit description)
// and are baked in as UTF-8 byte literals so this test has no external
// dependency at build or run time.
// =============================================================================
#include "tokenizer.hpp"
#include <cstdio>
#include <vector>
#include <string>

using namespace vlrf;

static int g_pass = 0, g_fail = 0;

static void check_split(const char* label, std::string const& input,
                         std::vector<std::string> const& expected) {
    auto got = gpt2_pretokenize::split(input);
    if (got == expected) {
        printf("  PASS  %s\n", label);
        ++g_pass;
    } else {
        printf("  FAIL  %s\n", label);
        printf("    expected (%zu chunks): ", expected.size());
        for (auto const& s : expected) printf("[%s] ", s.c_str());
        printf("\n    got      (%zu chunks): ", got.size());
        for (auto const& s : got) printf("[%s] ", s.c_str());
        printf("\n");
        ++g_fail;
    }
}

